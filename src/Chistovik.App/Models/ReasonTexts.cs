    /// <summary>
    /// Описание области в «Чистке». Для реестра здесь же сноска про поддержку Microsoft (статья KB 2563254):
    /// это честное предупреждение, а не повод отказаться от функции, поэтому чистим только записи с доказательством.
    /// </summary>
    public const string RegistryAreaDescription =
        "Microsoft не поддерживает чистильщики реестра (статья KB 2563254). Поэтому Чистовик предлагает убрать только записи, "
        + "про которые доказано, что программы или файла уже нет, а перед удалением сохраняет копию, чтобы вернуть запись из журнала.";

    public const string DiskAreaDescription =
        "Кэши и временные файлы, которые программы и Windows создают заново. Удаление необратимо, но чистятся только проверенные папки.";

    public static string AreaDescription(Chistovik.Core.Findings.FindingArea area) => area switch
    {
        Chistovik.Core.Findings.FindingArea.Registry => RegistryAreaDescription,
        Chistovik.Core.Findings.FindingArea.Disk => DiskAreaDescription,
        _ => "",
    };

    /// <summary>true — для кода есть собственный текст.</summary>
    public static bool IsKnown(string? rule) => !string.IsNullOrEmpty(rule) && Map.ContainsKey(rule);

    /// <summary>Объяснение причины. Неизвестный или пустой код даёт общий текст «система не уверена».</summary>
    public static string Explain(string? rule) => !string.IsNullOrEmpty(rule) && Map.TryGetValue(rule, out var text) ? text : Unsure;

    /// <summary>Для объектов, которые можно менять, объяснение причины не нужно: берётся пояснение политики.</summary>
    public static string ExplainOrKeep(Changeability cls, string? rule, string policyReason)
        => cls == Changeability.Modifiable ? policyReason : Explain(rule);
